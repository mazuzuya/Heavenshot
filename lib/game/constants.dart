// Semua area setinggi [areaHeight] berurutan dari 0, jadi indeks bisa dihitung
// langsung tanpa memindai daftar (fungsi ini dipanggil ratusan kali per frame).
int zoneAt(double height) {
  if (height.isNaN || height < 0) return 0;
  final index = (height / areaHeight).floor();
  return index >= zones.length ? zones.length - 1 : index;
}

int scaledEnemyHp(int baseHp, int areaIndex) =>
    (baseHp * (130 + areaIndex * 10) + 99) ~/ 100;

